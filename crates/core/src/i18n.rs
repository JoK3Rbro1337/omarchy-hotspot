#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_lang() {
        assert_eq!(Lang::parse("uk_UA.UTF-8"), Some(Lang::Uk));
        assert_eq!(Lang::parse("en"), Some(Lang::En));
        assert_eq!(Lang::parse("de_DE"), None);
        assert_eq!(Lang::parse("r"), None);
    }

    #[test]
    fn all_languages_non_empty() {
        for m in [Msg::Yes, Msg::DoctorTitle, Msg::AdviceNoAp] {
            for l in [Lang::Ru, Lang::Uk, Lang::En] {
                assert!(!t(l, m).is_empty());
            }
        }
    }

    #[test]
    fn formats_args_once() {
        assert_eq!(
            tf(Lang::En, Msg::OnStarted, &["a{}b"]),
            "Hotspot is on: network \"a{}b\""
        );
        assert_eq!(tf(Lang::Ru, Msg::UptimeFmt, &["1", "5"]), "1 ч 5 мин");
    }
}
