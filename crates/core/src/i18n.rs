pub fn t(lang: Lang, msg: Msg) -> &'static str {
    let [ru, uk, en] = table(msg);
    match lang {
        Lang::Ru => ru,
        Lang::Uk => uk,
        Lang::En => en,
    }
}

/// Подстановка аргументов вместо `{}` по порядку. Аргументы повторно не разбираются.
pub fn tf(lang: Lang, msg: Msg, args: &[&str]) -> String {
    let mut out = String::new();
    let mut parts = t(lang, msg).split("{}");
    if let Some(first) = parts.next() {
        out.push_str(first);
    }
    for (i, part) in parts.enumerate() {
        out.push_str(args.get(i).copied().unwrap_or(""));
        out.push_str(part);
    }
    out
}

