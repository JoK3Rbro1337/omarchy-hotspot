//! Тексты для пользователя. Порядок в таблице: ru, uk, en.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Lang {
    #[default]
    Ru,
    Uk,
    En,
}

impl Lang {
    pub fn parse(s: &str) -> Option<Lang> {
        match s.to_ascii_lowercase().get(..2)? {
            "ru" => Some(Lang::Ru),
            "uk" => Some(Lang::Uk),
            "en" => Some(Lang::En),
            _ => None,
        }
    }

    /// Язык из `$LANG`; если не распознан — русский.
    pub fn from_env() -> Lang {
        std::env::var("LANG")
            .ok()
            .and_then(|v| Lang::parse(&v))
            .unwrap_or_default()
    }
}

